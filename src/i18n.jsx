function interpolate(str, vars) {
  if (!vars) return str;
  return str.replace(/\{\{(\w+)\}\}/g, (_, k) => (vars[k] ?? ""));
}

function resolve(value, vars) {
  if (value && typeof value === "object") {
    const count = vars?.count;
    value = count === 1 ? value.one : value.other;
  }
  return typeof value === "string" ? interpolate(value, vars) : value;
}

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem("lang") || "sq");

  const setLang = useCallback((next) => {
    setLangState(next);
    localStorage.setItem("lang", next);
  }, []);

  const t = useCallback(
    (key, vars) => {
      // de/fr/it only cover the client-facing surface (see the comment above their blocks) --
      // anything missing there (business/admin/analytics/legal pages) falls back to English first,
      // since that's a closer read for a foreign user than Albanian, before finally falling back
      // to Albanian (which is always complete).
      const raw = TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? TRANSLATIONS.sq[key];
      return raw !== undefined ? resolve(raw, vars) : key;
    },
    [lang]
  );

  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>;
}
